"""Generate portable Codex adapters from canonical persona Markdown and one template."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
import tomllib


SCRIPT_ROOT = Path(__file__).resolve().parent
DEFAULT_ROOT = SCRIPT_ROOT.parent


def section(markdown: str, heading: str) -> str:
    match = re.search(r"^## " + re.escape(heading) + r"\s*\n(.*?)(?=^## |\Z)",
                      markdown, re.MULTILINE | re.DOTALL)
    if not match or not match.group(1).strip():
        raise ValueError(f"Missing persona section: {heading}")
    return match.group(1).strip()


def generate(repo_root: Path = DEFAULT_ROOT) -> dict[Path, str]:
    """Return all expected outputs; validate every input before any file is written."""
    scripts = repo_root / "scripts"
    manifest = json.loads((scripts / "persona-adapters.json").read_text(encoding="utf-8"))
    template = (scripts / "persona-adapter-template.txt").read_text(encoding="utf-8")
    outputs = {}
    for name, description in sorted(manifest.items()):
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*-persona", name):
            raise ValueError(f"Invalid persona name: {name}")
        bundle = repo_root / "source" / "agents" / name
        markdown = (bundle / "AGENT.md").read_text(encoding="utf-8")
        if not re.search(r"^name: " + re.escape(name) + r"$", markdown, re.MULTILINE):
            raise ValueError(f"Canonical name mismatch: {name}")
        title = re.search(r"^# (.+)$", markdown, re.MULTILINE)
        if title is None:
            raise ValueError(f"Missing persona title: {name}")
        combinations = section(markdown, "Typical Reference Combinations")
        references = re.findall(r"`([a-z0-9-]+\.md)`", combinations)
        if not references:
            raise ValueError(f"Missing focused references: {name}")
        for reference in references:
            if not (bundle / "references" / reference).is_file():
                raise ValueError(f"Missing reference: {name}/{reference}")
        instructions = template.format(
            name=name, title=title.group(1),
            best_fit=section(markdown, "Best Fit"),
            other_agent=section(markdown, "Use Another Primary Agent When"),
            stance=section(markdown, "Operating Principles" if name == "quality-gate-persona"
                           else "Default Stance"),
            combinations=combinations, avoid=section(markdown, "Avoid"),
        )
        # A TOML literal multiline string preserves backslashes and quoted identifiers.
        if "'''" in instructions:
            raise ValueError(f"Unsupported TOML delimiter in {name}")
        output = (
            "# Generated by scripts/generate_persona_adapters.py; edit canonical inputs.\n"
            f"name = {json.dumps(name)}\n"
            f"description = {json.dumps(description)}\n\n"
            f"developer_instructions = '''\n{instructions.rstrip()}\n'''\n"
        )
        tomllib.loads(output)
        outputs[repo_root / "source" / "agents" / f"{name}.toml"] = output
    return outputs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--check", action="store_true", help="Report drift without writing files")
    args = parser.parse_args(argv)
    try:
        outputs = generate(args.repo_root.resolve())
    except (OSError, ValueError, KeyError, tomllib.TOMLDecodeError) as error:
        print(f"Persona generation failed: {error}", file=sys.stderr)
        return 2
    drift = []
    for path, content in outputs.items():
        if args.check:
            # Git's Windows checkout may convert LF to CRLF. Only normalize line
            # endings; trailing whitespace and all other content still constitute drift.
            if not path.is_file() or path.read_bytes().replace(b"\r\n", b"\n") != content.encode("utf-8"):
                drift.append(path.name)
        else:
            path.write_bytes(content.encode("utf-8"))
    if drift:
        print("Persona adapter drift: " + ", ".join(drift), file=sys.stderr)
        return 1
    print(f"Persona adapters: {len(outputs)} {'checked' if args.check else 'generated'}; zero drift")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
